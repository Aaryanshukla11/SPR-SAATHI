class SpecialistDelegator:
    """
    Phase 12: Specialist Delegation and Orchestration Engine.
    
    Detects tasks matching specialist domains and delegates execution,
    providing result verification and graceful fallback.
    """

    def __init__(self):
        self._specialists: Dict[SpecialistType, BaseSpecialist] = {
            SpecialistType.CODING: KairoCodingSpecialist(),
            SpecialistType.RESEARCH: ResearchSpecialist(),
            SpecialistType.DATA_ANALYSIS: DataAnalysisSpecialist()
        }

    def register_specialist(self, specialist: BaseSpecialist):
        self._specialists[specialist.specialist_type] = specialist

    def detect_specialist(self, task: str) -> Optional[BaseSpecialist]:
        """Detects whether a specialized system should handle the task."""
        # Check Coding first (KAIRO-AI)
        coding_spec = self._specialists.get(SpecialistType.CODING)
        if coding_spec and coding_spec.can_handle(task):
            return coding_spec

        for spec in self._specialists.values():
            if spec.can_handle(task):
                return spec
        return None

    async def delegate_task(
        self,
        task: str,
        context: Optional[Dict[str, Any]] = None
    ) -> Optional[SpecialistResult]:
        """
        Delegates task to specialist. Falls back gracefully if specialist fails.
        """
        specialist = self.detect_specialist(task)
        if not specialist:
            return None

        try:
            logger.info(f"Delegating task to specialist '{specialist.name}'")
            res = await specialist.execute(task, context)
            return res
        except Exception as e:
            logger.error(f"Specialist '{specialist.name}' failed: {e}. Falling back to general agent.")
            return SpecialistResult(
                specialist_name=specialist.name,
                specialist_type=specialist.specialist_type,
                success=False,
                output=None,
                verification_passed=False,
                error=str(e)
            )


# Global singleton instance
SPECIALIST_DELEGATOR = SpecialistDelegator()
